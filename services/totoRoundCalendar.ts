export const TOTO_ROUND_CALENDAR: TotoRoundCalendarEntry[] = RAW_ROUND_DATES.trim()
  .split("\n")
  .map((line) => {
    const [roundNo, date] = line.trim().split(/\s+/);
    return { roundNo, date };
  });

export const TOTO_ROUND_DATE_BY_NO = new Map(
  TOTO_ROUND_CALENDAR.map((entry) => [entry.roundNo, entry.date])
);

export const TOTO_BACKTEST_ROUNDS = TOTO_ROUND_CALENDAR.map(
  (entry) => entry.roundNo
);

export function getTotoRoundDate(roundNo: string | number): string | null {
  return TOTO_ROUND_DATE_BY_NO.get(String(roundNo).replace(/[^\d]/g, "")) ?? null;
}

export function buildKnownRoundRange(
  from?: string | number,
  to?: string | number
): string[] {
  const start = Number(from ?? TOTO_BACKTEST_ROUNDS[TOTO_BACKTEST_ROUNDS.length - 1]);
  const end = Number(to ?? TOTO_BACKTEST_ROUNDS[0]);

  if (!Number.isInteger(start) || !Number.isInteger(end)) {
    return TOTO_BACKTEST_ROUNDS;
  }

  const min = Math.min(start, end);
  const max = Math.max(start, end);

  return TOTO_BACKTEST_ROUNDS.filter((roundNo) => {
    const n = Number(roundNo);
    return n >= min && n <= max;
  });
}
